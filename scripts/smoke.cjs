const { _electron: electron, expect } = require('playwright/test')
const { mkdir, writeFile } = require('node:fs/promises')
const { join } = require('node:path')
const assert = require('node:assert/strict')

async function run() {
  const output = join(__dirname, '../test-results'); await mkdir(output, { recursive: true })
  const packaged = process.argv.includes('--packaged')
  const app = await electron.launch({
    executablePath: packaged ? join(__dirname, '../release/win-unpacked/NoteBlock Editor.exe') : require('electron'),
    args: packaged ? [] : [join(__dirname, '..')],
    env: { ...process.env, NBE_SMOKE_TEST: '1', ELECTRON_ENABLE_LOGGING: '1' }, timeout: 30000
  })
  const checks = [], errors = []
  try {
    const main = await app.firstWindow()
    await app.evaluate(({ BrowserWindow }) => { for (const win of BrowserWindow.getAllWindows()) win.showInactive() })
    main.on('pageerror', e => errors.push(e.message))
    await main.getByTestId('playlist-grid').waitFor()
    assert.equal(await main.getByTestId('instrument-palette').count(), 0)
    checks.push('主窗口无音色栏')
    const isolation = await main.evaluate(() => ({ node: typeof window.require, api: Object.keys(window.editor).sort() }))
    assert.equal(isolation.node, 'undefined'); assert.deepEqual(isolation.api, ['dispatch','getSnapshot','onSnapshot','openPatternWindow','readNoteClipboard','writeNoteClipboard'])
    checks.push('渲染进程无 Node 权限，preload 仅公开业务 API')
    await main.screenshot({ path: join(output, 'desktop-playlist.png') })
    await main.getByTestId('pattern-p1').dblclick()
    await expect(main.getByTestId('floating-editor')).toBeVisible()
    await expect(main.locator('.instrument')).toHaveCount(16)
    const bounds = await main.getByTestId('floating-editor').boundingBox()
    assert.ok(bounds.width > 680 && bounds.height > 400)
    await main.getByRole('button', { name: '最小化', exact: true }).click()
    assert.equal(await main.getByTestId('instrument-palette').count(), 0)
    await main.locator('.window-dock button').click()
    await expect(main.getByTestId('instrument-palette')).toBeVisible()
    checks.push('内部编辑器打开、最小化、恢复；16 音色只在子窗口内')
    await main.getByRole('button', { name: '最大化或还原' }).click()
    await expect(main.getByTestId('floating-editor')).toHaveClass(/maximized/)
    await main.getByRole('button', { name: '最大化或还原' }).click()
    const header = main.locator('.window-title'), hb = await header.boundingBox()
    await main.mouse.move(hb.x + 180, hb.y + 14); await main.mouse.down(); await main.mouse.move(hb.x + 215, hb.y + 34); await main.mouse.up()
    const moved = await main.getByTestId('floating-editor').boundingBox()
    assert.ok(moved.x > bounds.x + 20 && moved.y > bounds.y + 10)
    checks.push('内部窗口最大化、还原、标题栏拖动')
    await main.screenshot({ path: join(output, 'desktop-pattern.png') })
    const original = await main.evaluate(() => window.editor.getSnapshot())
    const grid = main.getByTestId('note-grid'), gb = await grid.boundingBox()
    await main.mouse.click(gb.x + 106 + 3 * 25 + 12, gb.y + 26 + 3 * 39 + 18)
    await expect.poll(() => main.evaluate(() => window.editor.getSnapshot().then(s => s.project.patterns[0].notes.length))).toBe(original.project.patterns[0].notes.length + 1)
    await main.mouse.click(gb.x + 106 + 3 * 25 + 12, gb.y + 26 + 3 * 39 + 18, { button: 'right' })
    await expect.poll(() => main.evaluate(() => window.editor.getSnapshot().then(s => s.project.patterns[0].notes.length))).toBe(original.project.patterns[0].notes.length)
    checks.push('真实鼠标左键放置 / 右键删除音符')
    const firstId = original.project.patterns[0].notes[0].id
    await main.mouse.move(gb.x + 118, gb.y + 44); await main.mouse.down(); await main.mouse.move(gb.x + 143, gb.y + 44); await main.mouse.up()
    await expect.poll(() => main.evaluate(id => window.editor.getSnapshot().then(s => s.project.patterns[0].notes.find(n => n.id === id).tick), firstId)).toBe(1)
    await main.keyboard.press('Control+z')
    await expect.poll(() => main.evaluate(id => window.editor.getSnapshot().then(s => s.project.patterns[0].notes.find(n => n.id === id).tick), firstId)).toBe(0)
    checks.push('音符拖动实际提交，Ctrl+Z 一次撤销整个拖动')
    await main.keyboard.press('Control+c')
    const ruler = await main.getByTestId('note-ruler').boundingBox()
    await main.mouse.click(ruler.x + 106 + 25 + 12, ruler.y + 12)
    await main.keyboard.press('Control+v')
    await expect.poll(() => main.evaluate(() => window.editor.getSnapshot().then(s => s.project.patterns[0].notes.length))).toBe(original.project.patterns[0].notes.length + 1)
    await main.keyboard.press('Control+x')
    await expect.poll(() => main.evaluate(() => window.editor.getSnapshot().then(s => s.project.patterns[0].notes.length))).toBe(original.project.patterns[0].notes.length)
    checks.push('时间标尺设定粘贴位置；键盘复制、粘贴、剪切')
    await main.mouse.click(gb.x + 118, gb.y + 44)
    const velocity = main.getByRole('slider', { name: '音符力度' }), oldVelocity = Number(await velocity.inputValue())
    await velocity.focus(); await main.keyboard.press('ArrowLeft')
    await expect.poll(() => main.evaluate(id => window.editor.getSnapshot().then(s => s.project.patterns[0].notes.find(n => n.id === id).velocity), firstId)).toBe(oldVelocity - 1)
    checks.push('力度滑杆的键盘操作写入所选音符')
    await main.getByRole('button', { name: '钢琴卷帘', exact: true }).click()
    assert.ok(await main.locator('.note-scroll').evaluate(el => el.scrollHeight) >= 88 * 22)
    await expect(main.getByTestId('note-ruler')).toBeVisible()
    await main.screenshot({ path: join(output, 'desktop-piano.png') })
    await main.getByRole('button', { name: '图层', exact: true }).click()
    const childPromise = app.waitForEvent('window')
    await main.getByRole('button', { name: '弹出为桌面窗口' }).click()
    const child = await childPromise
    await app.evaluate(({ BrowserWindow }) => { for (const win of BrowserWindow.getAllWindows()) win.showInactive() })
    child.on('pageerror', e => errors.push(e.message))
    await child.getByTestId('instrument-palette').waitFor()
    assert.equal((await child.evaluate(() => window.editor.readNoteClipboard())).length, 1)
    assert.equal(await main.getByTestId('instrument-palette').count(), 0)
    await main.evaluate(() => window.editor.openPatternWindow('p1'))
    assert.equal(app.windows().length, 2)
    checks.push('弹出原生编辑窗口，同 Pattern 重复打开不新建')
    const before = await child.evaluate(() => window.editor.getSnapshot())
    const noteId = before.project.patterns[0].notes[0].id
    await child.evaluate(id => window.editor.dispatch({ type: 'set-note-properties', patternId: 'p1', ids: [id], velocity: 61 }), noteId)
    await expect.poll(() => main.locator('.app').getAttribute('data-revision')).toBe(String(before.revision + 1))
    const shared = await main.evaluate(() => window.editor.getSnapshot())
    assert.equal(shared.project.patterns[0].notes[0].velocity, 61)
    let invalidRejected = false
    try { await child.evaluate(() => window.editor.dispatch({ type: 'add-note', patternId: 'p1', tick: -1, layer: 0, pitch: 60, instrument: 0, velocity: 80 })) } catch { invalidRejected = true }
    assert.ok(invalidRejected)
    assert.equal((await main.evaluate(() => window.editor.getSnapshot())).revision, shared.revision)
    checks.push('原生子窗编辑广播至主窗，非法 IPC 命令不改变工程')
    const samples = await child.evaluate(async () => {
      const names = ['harp','dbass','bdrum','sdrum','click','guitar','flute','bell','icechime','xylobone','iron_xylophone','cow_bell','didgeridoo','bit','banjo','pling']
      const context = new AudioContext()
      try { return await Promise.all(names.map(async name => {
        const response = await fetch(new URL('./sounds/' + name + '.ogg', document.baseURI)), bytes = await response.arrayBuffer()
        const hash = [...new Uint8Array(await crypto.subtle.digest('SHA-256', bytes))].map(b => b.toString(16).padStart(2,'0')).join('')
        const buffer = await context.decodeAudioData(bytes)
        return { name, bytes: bytes.byteLength, hash, duration: buffer.duration }
      })) } finally { await context.close() }
    })
    const fs = require('node:fs'), crypto = require('node:crypto')
    for (const sample of samples) {
      assert.ok(sample.duration > .04)
      const bytes = fs.readFileSync(join(__dirname, '../src/renderer/public/sounds', sample.name + '.ogg'))
      assert.equal(sample.hash, crypto.createHash('sha256').update(bytes).digest('hex'))
    }
    checks.push('16 个本地 OGG 在实际 Electron 中逐一解码及 SHA-256 比对')
    await child.screenshot({ path: join(output, 'desktop-native-pattern.png') })
    await child.close()
    const reopenedPromise = app.waitForEvent('window')
    await main.evaluate(() => window.editor.openPatternWindow('p1'))
    const reopened = await reopenedPromise
    await reopened.getByTestId('pattern-editor').waitFor()
    assert.equal((await reopened.evaluate(() => window.editor.getSnapshot())).project.patterns[0].notes[0].velocity, 61)
    assert.equal((await reopened.evaluate(() => window.editor.readNoteClipboard())).length, 1)
    checks.push('关闭 / 重开原生子窗口保留编辑与共享剪贴板')
    assert.deepEqual(errors, [])
    await writeFile(join(output, packaged ? 'smoke-packaged.json' : 'smoke.json'), JSON.stringify({ packaged, checks, samples, errors }, null, 2))
    console.log(JSON.stringify({ packaged, passed: checks.length, checks, errors }, null, 2))
  } finally { await app.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
